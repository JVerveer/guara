create table if not exists gold_bouwen_wonen.fact_housing_observation (
  housing_observation_key bigint generated by default as identity primary key,
  observation_key bigint,
  housing_dataset_key bigint not null references gold_bouwen_wonen.dim_housing_dataset(housing_dataset_key),
  housing_indicator_key bigint not null references gold_bouwen_wonen.dim_housing_indicator(housing_indicator_key),
