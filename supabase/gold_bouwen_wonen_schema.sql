  measure_key bigint not null references gold.dim_measure(measure_key),
  date_key bigint not null references gold.dim_date(date_key),
  geography_key bigint not null references gold.dim_geography(geography_key),
  unit_key bigint not null references gold.dim_unit(unit_key),
  calendar_year integer,
  period_code text,
  period_type text,
  geography_code text,
  geography_name text,
  geography_type text,
  municipality_code text,
  province_code text,
  country_code text,
  observation_value numeric,
  observation_text text,
  status_code text,
  is_missing boolean not null default false,
  is_suppressed boolean not null default false,
  category_combination_hash text not null,
  source_observation_id text,
  silver_observation_id text,
  bronze_record_id text,
  record_hash text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (observation_key)
);

do $$
declare
  constraint_name text;
begin
  for constraint_name in
    select c.conname
    from pg_constraint c
    join pg_class t on t.oid = c.conrelid
    join pg_namespace n on n.oid = t.relnamespace
    join pg_class rt on rt.oid = c.confrelid
    join pg_namespace rn on rn.oid = rt.relnamespace
    where n.nspname = 'gold_bouwen_wonen'
      and t.relname = 'fact_housing_observation'
      and c.contype = 'f'
      and rn.nspname = 'gold'
      and rt.relname = 'fact_observation'
  loop
    execute format('alter table gold_bouwen_wonen.fact_housing_observation drop constraint if exists %I', constraint_name);
  end loop;
end $$;

