create or replace function public.guara_semantic_aggregation_sandbox(
  p_domain text,
  p_dataset_code text,
  p_measure_key text,
  p_calendar_year integer default null,
  p_geography_type text default null,
  p_aggregation text default 'sum',
  p_category_filters jsonb default '{}'::jsonb,
  p_group_dimension text default null,
  p_limit integer default 25
)
returns jsonb
language plpgsql
stable
security definer
set search_path = semantic, gold, public
as $$
declare
  result jsonb;
  agg text := lower(coalesce(nullif(p_aggregation, ''), 'sum'));
  aggregate_expression text;
  generated_sql text;
begin
  if agg not in ('sum', 'avg', 'average', 'min', 'max', 'count') then
    raise exception 'Unsupported aggregation: %', p_aggregation;
  end if;

  aggregate_expression := case
    when agg = 'count' then 'count(*)::numeric'
    when agg in ('avg', 'average') then 'avg(f.observation_value)'
    when agg = 'min' then 'min(f.observation_value)'
