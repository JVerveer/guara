          else array[value #>> '{}']
        end as category_values
      from jsonb_each(coalesce(p_category_filters, '{}'::jsonb))
    ),
    filter_count as materialized (
      select count(*)::integer as value
      from required_filters
    ),
    dataset_for_totals as materialized (
