  p_domain text default null,
  p_status text default null,
  p_query text default null,
  p_limit integer default 300
)
returns jsonb
language sql
stable
security definer
set search_path = semantic, gold, public
as $$
  with mart_measures as (
    select
      'bouwen-en-wonen'::text as domain_id,
      d.dataset_code,
      i.measure_key,
      i.measure_code,
      i.indicator_name as measure_name,
      i.indicator_description as measure_description,
      i.topic,
      i.subtopic,
      i.unit_code,
      i.unit_name,
      i.default_aggregation,
      i.value_type,
      i.is_additive,
      i.is_non_additive,
      d.dataset_title,
      d.source_system,
      d.source_organization,
      d.source_url,
      d.last_updated_at_source,
      d.updated_at as gold_loaded_at
    from gold_bouwen_wonen.dim_housing_indicator i
    join gold_bouwen_wonen.dim_housing_dataset d on d.dataset_key = i.dataset_key
    union all
    select
      'inkomen-en-bestedingen'::text as domain_id,
      d.dataset_code,
      i.measure_key,
      i.measure_code,
      i.indicator_name as measure_name,
      i.indicator_description as measure_description,
      i.topic,
      i.subtopic,
      i.unit_code,
      i.unit_name,
      i.default_aggregation,
      i.value_type,
      i.is_additive,
      i.is_non_additive,
      d.dataset_title,
      d.source_system,
      d.source_organization,
      d.source_url,
      d.last_updated_at_source,
      d.updated_at as gold_loaded_at
    from gold_inkomen_bestedingen.dim_income_indicator i
    join gold_inkomen_bestedingen.dim_income_dataset d on d.dataset_key = i.dataset_key
  ),
  capabilities as (
    select
      m.domain_id,
      m.dataset_code,
      m.measure_key,
      m.measure_code,
      m.measure_name,
      m.measure_description,
      m.topic,
      m.subtopic,
      m.unit_code,
      m.unit_name,
      m.default_aggregation,
      m.value_type,
      m.is_additive,
      m.is_non_additive,
      coalesce(c.populated_fact_rows, p.populated_fact_rows, 0)::bigint as populated_fact_rows,
      coalesce(c.loaded_fact_rows, p.loaded_fact_rows, 0)::bigint as loaded_fact_rows,
      case
        when c.capability_id is not null then 'counted'
        when coalesce(p.populated_fact_rows, 0) > 0 then 'available_not_counted'
        else 'no_facts_found'
      end as fact_row_count_status,
      coalesce(c.min_year, p.min_year) as min_year,
      coalesce(c.max_year, p.max_year) as max_year,
      coalesce(nullif(c.available_years, '{}'::integer[]), p.available_years, '{}'::integer[]) as available_years,
      coalesce((
        select array_agg(distinct normalized_level order by normalized_level)
        from (
          select case
            when raw_level in ('national', 'unknown') then 'country'
            else raw_level
          end as normalized_level
          from unnest(coalesce(nullif(p.geography_types, '{}'::text[]), c.geography_types, '{}'::text[])) raw_level
          where nullif(raw_level, '') is not null
        ) normalized_levels
      ), '{}'::text[]) as geography_types,
      coalesce((
        select array_agg(distinct normalized_grain order by normalized_grain)
        from (
          select regexp_replace(raw_grain, '^national_', 'country_') as normalized_grain
          from unnest(coalesce(nullif(p.grains, '{}'::text[]), c.grains, '{}'::text[])) raw_grain
          where nullif(raw_grain, '') is not null
        ) normalized_grains
      ), '{}'::text[]) as grains,
      coalesce(c.supports_ranking, false) as supports_ranking,
      coalesce(c.supports_trend, false) as supports_trend,
      coalesce(c.supports_comparison, false) as supports_comparison,
      coalesce(c.executable_candidate, false) as executable_candidate,
      coalesce(c.non_executable_reasons, '{}'::text[]) as non_executable_reasons,
      coalesce(c.metadata, '{}'::jsonb) as metadata,
      m.dataset_title,
      m.source_system,
      m.source_organization,
      m.source_url,
      m.last_updated_at_source,
      m.gold_loaded_at,
      mc.metric_code,
      mc.contract_status,
      mc.execution_status,
      mc.semantic_quality_status,
      mc.metadata_origin,
      mc.default_grain,
      mc.valid_grains,
      mc.supports,
      r.review_status,
      r.risk_level,
      r.execution_recommendation,
      r.priority_score,
      r.diagnostic_summary,
      case
        when mc.execution_status = 'enabled' and mc.contract_status in ('reviewed', 'curated') then 'approved'
        when r.review_status = 'review_candidate' then 'under_review'
        when r.review_status = 'needs_fix' then 'needs_fix'
        when mc.metric_code is not null then coalesce(mc.contract_status, 'profiled')
        when c.capability_id is not null or p.measure_key is not null then 'gold_profiled'
        else 'gold_modeled'
      end as approval_status
    from mart_measures m
    left join semantic.gold_measure_capability c
      on c.domain_id = m.domain_id
     and c.dataset_code = m.dataset_code
     and c.measure_key = m.measure_key
    left join semantic.workbench_measure_profile p
      on p.domain_id = m.domain_id
     and p.dataset_code = m.dataset_code
     and p.measure_key = m.measure_key
    left join lateral (
      select mc.*
      from semantic.metric_contract mc
      where mc.domain_id = m.domain_id
        and mc.measure_key = m.measure_key
        and m.dataset_code = any(mc.dataset_codes)
        and mc.is_active
      order by
        case when mc.execution_status = 'enabled' and mc.contract_status in ('reviewed', 'curated') then 0 else 1 end,
        case when mc.metadata_origin = 'curated' then 0 else 1 end,
        mc.selection_priority,
        mc.updated_at desc
      limit 1
    ) mc on true
    left join semantic.metric_contract_review r on r.metric_code = mc.metric_code
    where m.domain_id in ('bouwen-en-wonen', 'inkomen-en-bestedingen')
      and (nullif(p_domain, '') is null or p_domain = 'all' or m.domain_id = p_domain)
      and (
        nullif(p_query, '') is null
        or m.dataset_code ilike '%' || p_query || '%'
        or m.measure_name ilike '%' || p_query || '%'
        or coalesce(m.measure_code, '') ilike '%' || p_query || '%'
        or coalesce(mc.metric_code, '') ilike '%' || p_query || '%'
        or coalesce(m.dataset_title, '') ilike '%' || p_query || '%'
      )
  ),
  filtered as (
    select *
    from capabilities
    where (nullif(p_status, '') is null or p_status = 'all' or approval_status = p_status)
    order by
      case approval_status
        when 'approved' then 0
        when 'under_review' then 1
        when 'needs_fix' then 2
        when 'profiled' then 3
        when 'gold_profiled' then 4
        when 'gold_modeled' then 5
        else 4
      end,
      populated_fact_rows desc nulls last,
      dataset_code,
      measure_name
    limit least(greatest(coalesce(p_limit, 300), 1), 5000)
  )
  select jsonb_build_object(
    'items', coalesce(jsonb_agg(to_jsonb(filtered) || jsonb_build_object('measure_key', filtered.measure_key::text)), '[]'::jsonb),
    'summary', coalesce((
      select jsonb_object_agg(approval_status, item_count)
      from (
        select approval_status, count(*) as item_count
        from capabilities
        group by approval_status
      ) counts
    ), '{}'::jsonb)
  )
  from filtered;
$$;

