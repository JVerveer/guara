create or replace function public.guara_semantic_review_queue(
  p_domain text default null,
  p_status text default null,
  p_risk text default null,
  p_query text default null,
  p_limit integer default 150
)
returns jsonb
language sql
stable
security definer
set search_path = semantic, public
as $$
  with review_rows as materialized (
    select
      r.*,
      row_number() over (order by r.priority_score asc, r.updated_at desc, r.metric_code asc) as sort_order
    from semantic.metric_contract_review r
    where (nullif(p_domain, '') is null or p_domain = 'all' or r.domain_id = p_domain)
      and (nullif(p_status, '') is null or p_status = 'all' or r.review_status = p_status)
      and (nullif(p_risk, '') is null or p_risk = 'all' or r.risk_level = p_risk)
      and (
        nullif(p_query, '') is null
        or r.metric_code ilike '%' || p_query || '%'
        or r.label ilike '%' || p_query || '%'
        or r.dataset_code ilike '%' || p_query || '%'
        or r.domain_id ilike '%' || p_query || '%'
        or coalesce(r.measure_code, '') ilike '%' || p_query || '%'
      )
    order by r.priority_score asc, r.updated_at desc, r.metric_code asc
    limit least(greatest(coalesce(p_limit, 150), 1), 500)
  ),
  metric_codes as (
    select coalesce(array_agg(metric_code), '{}'::text[]) as codes
    from review_rows
  )
  select jsonb_build_object(
    'reviews',
      coalesce((
        select jsonb_agg(to_jsonb(r) - 'sort_order' order by r.sort_order)
        from review_rows r
      ), '[]'::jsonb),
    'diagnostics',
      coalesce((
        select jsonb_agg(to_jsonb(d) order by d.is_blocking desc, d.severity asc, d.diagnostic_code asc)
        from semantic.metric_contract_diagnostic d
        cross join metric_codes m
        where d.metric_code = any(m.codes)
      ), '[]'::jsonb),
    'testCases',
      coalesce((
        select jsonb_agg(to_jsonb(t) order by t.created_at asc, t.metric_contract_test_case_id asc)
        from semantic.metric_contract_test_case t
        cross join metric_codes m
        where t.metric_code = any(m.codes)
      ), '[]'::jsonb),
    'promotionEvents',
      coalesce((
        select jsonb_agg(to_jsonb(e) order by e.created_at desc, e.promotion_event_id desc)
        from (
          select e.*
          from semantic.metric_contract_promotion_event e
          cross join metric_codes m
          where e.metric_code = any(m.codes)
          order by e.created_at desc, e.promotion_event_id desc
          limit 50
        ) e
      ), '[]'::jsonb)
  );
$$;

